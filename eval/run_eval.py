"""Eval runner. Uploads the six images, asks every case through /ask, scores, writes reports.

Prerequisites:
  1. Server running on --base-url with the SAME database as --db (fresh, holds only these images).
  2. API_KEY set in the environment to the server's key.
  3. Images in --images (default data/images), named test1.jpg to test6.jpg.

Usage:
  python eval/run_eval.py --base-url http://127.0.0.1:8000 --db data/eval.db --images data/images

The rate limiter allows 20 /ask calls per minute per key. The runner waits and retries on 429,
and records the retry count. Retries are not failures.
"""
import argparse
import json
import os
import sqlite3
import sys
import time
from contextlib import closing
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from eval.score import percentile, score_row, validate_cases  # noqa: E402

EVAL_DIR = Path(__file__).resolve().parent
IMAGE_NAMES = [f"test{i}.jpg" for i in range(1, 7)]
RETRY_WAIT_S = 3.5
MAX_RETRIES = 5


def load_cases(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def post_with_retry(client, url, sleep=time.sleep, **kwargs):
    """Retry only on HTTP 429. Returns (response, retries, duration_ms of the final attempt)."""
    retries = 0
    while True:
        t0 = time.perf_counter()
        r = client.post(url, **kwargs)
        duration_ms = (time.perf_counter() - t0) * 1000
        if r.status_code != 429 or retries >= MAX_RETRIES:
            return r, retries, duration_ms
        retries += 1
        sleep(RETRY_WAIT_S)


def upload_images(client, images_dir):
    ids = {}
    for name in IMAGE_NAMES:
        with open(Path(images_dir) / name, "rb") as f:
            r = client.post("/detect", files={"file": (name, f, "image/jpeg")})
        r.raise_for_status()
        ids[name] = r.json()["image_id"]
    return ids


def image_count(db_path):
    with closing(sqlite3.connect(db_path)) as conn:
        return conn.execute("SELECT COUNT(*) FROM images").fetchone()[0]


def tool_trace(db_path, run_id):
    if not run_id:
        return []
    with closing(sqlite3.connect(db_path)) as conn:
        conn.row_factory = sqlite3.Row
        rows = conn.execute(
            "SELECT step, tool_name, args_json, ok, error, result_summary "
            "FROM tool_calls WHERE run_id = ? ORDER BY step, id", (run_id,)).fetchall()
    return [dict(r) for r in rows]


def run_all(client, cases, ids, id_to_name, db_path):
    results = []
    for case in cases:
        anchor = ids["test1.jpg"] if case["type"] == "cross" else ids[case["image"]]
        r, retries, duration_ms = post_with_retry(
            client, "/ask", json={"image_id": anchor, "question": case["question"]})
        body = r.json() if r.headers.get("content-type", "").startswith("application/json") else {}
        response = {"http_status": r.status_code, "body": body}
        verdict = score_row(case, response, id_to_name)
        results.append({
            "id": case["id"],
            "type": case["type"],
            "question": case["question"],
            "expected": case.get("expected"),
            "http_status": r.status_code,
            "status": body.get("status"),
            "answer": body.get("answer"),
            "run_id": body.get("run_id"),
            "latency_ms": round(duration_ms, 1),
            "retries": retries,
            "trace": tool_trace(db_path, body.get("run_id")),
            **verdict,
        })
        print(f"{case['id']:>4} {verdict['verdict']:<7} {r.status_code} retries={retries}")
    return results


def write_outputs(results, out_dir):
    out_dir = Path(out_dir)
    with open(out_dir / "results_v1.jsonl", "w", encoding="utf-8") as f:
        for row in results:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    (out_dir / "report_v1.md").write_text(build_report(results), encoding="utf-8")


def build_report(results):
    auto = [r for r in results if r["verdict"] in ("pass", "fail")]
    passed = [r for r in auto if r["verdict"] == "pass"]
    manual = [r for r in results if r["verdict"] == "manual"]
    fails = [r for r in results if r["verdict"] == "fail"]
    latencies = [r["latency_ms"] for r in results if r["run_id"]]
    lines = [
        "# Eval report v1 (generated by eval/run_eval.py; do not hand-edit)",
        "",
        f"Automatic: {len(passed)} pass, {len(auto) - len(passed)} fail of {len(auto)}.",
        f"Manual rows awaiting a human verdict: {len(manual)}.",
        f"/ask latency across {len(latencies)} runs: p50 "
        f"{percentile(latencies, 0.5)} ms, p95 {percentile(latencies, 0.95)} ms.",
        f"Rate-limit retries: {sum(r['retries'] for r in results)}.",
        "",
        "## Failures",
    ]
    if not fails:
        lines.append("None.")
    for r in fails:
        lines += [
            f"### {r['id']} ({r['type']})",
            f"- Question: {r['question']}",
            f"- Expected: {r['expected']}",
            f"- Answer: {r['answer']}",
            f"- Reason: {r['reason']}",
            f"- Trace: " + ("; ".join(
                f"step {t['step']} {t['tool_name']} ok={t['ok']} {t['error'] or ''}".strip()
                for t in r["trace"]) or "no tool calls"),
            "",
        ]
    lines += ["## Manual rows (fill in the verdict by hand)", ""]
    for r in manual:
        lines += [
            f"### {r['id']} ({r['type']})",
            f"- Question: {r['question']}",
            f"- Expected: {r['expected']}",
            f"- Answer: {r['answer']}",
            f"- Trace: " + ("; ".join(
                f"step {t['step']} {t['tool_name']} ok={t['ok']}" for t in r["trace"]) or "no tool calls"),
            "- Verdict: ______",
            "",
        ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Run the eval against a live server.")
    ap.add_argument("--base-url", default="http://127.0.0.1:8000")
    ap.add_argument("--db", default="data/eval.db")
    ap.add_argument("--images", default="data/images")
    ap.add_argument("--cases", default=str(EVAL_DIR / "cases.jsonl"))
    ap.add_argument("--out", default=str(EVAL_DIR))
    args = ap.parse_args()

    api_key = os.getenv("API_KEY")
    if not api_key:
        raise SystemExit("Set API_KEY in the environment to the server's key first.")

    cases = load_cases(args.cases)
    problems = validate_cases(cases)
    if problems:
        raise SystemExit("cases.jsonl is not ready:\n  " + "\n  ".join(problems))

    with httpx.Client(base_url=args.base_url, headers={"X-API-Key": api_key}, timeout=60) as client:
        ids = upload_images(client, args.images)
        count = image_count(args.db)
        if count != len(IMAGE_NAMES):
            raise SystemExit(
                f"{args.db} holds {count} images; expected exactly {len(IMAGE_NAMES)}. "
                "Cross-image answers are only valid on a database holding just the eval images.")
        id_to_name = {v: k for k, v in ids.items()}
        results = run_all(client, cases, ids, id_to_name, args.db)

    write_outputs(results, args.out)
    print(f"\nWrote {Path(args.out) / 'results_v1.jsonl'} and report_v1.md")


if __name__ == "__main__":
    main()
